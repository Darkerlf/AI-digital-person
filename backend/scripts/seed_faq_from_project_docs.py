def resolve_area(db, area_code: str) -> ScenicArea:
    area = db.query(ScenicArea).filter(ScenicArea.code == area_code).one_or_none()
    if area is not None:
        return area
    if area_code == "lingshan":
        area = db.query(ScenicArea).filter(ScenicArea.name == "灵山胜境").one_or_none()
    elif area_code == "NH":
        area = db.query(ScenicArea).filter(ScenicArea.name == "拈花湾禅意小镇").one_or_none()
    else:
        area = None
    if area is None:
        raise RuntimeError(f"Scenic area not found: {area_code}")
    return area


def main() -> None:
    db = SessionLocal()
    try:
        created = 0
        updated = 0
        for seed in FAQ_SEEDS:
            area = resolve_area(db, seed.area_code)
            faq = (
                db.query(FAQItem)
                .filter(
                    FAQItem.scenic_area_id == area.id,
                    FAQItem.question == seed.question,
                )
                .one_or_none()
            )
            payload = {
                "scenic_area_id": area.id,
                "question": seed.question,
                "answer": seed.answer,
                "category": seed.category,
                "priority": seed.priority,
                "status": "active",
                "source": SOURCE,
            }
            if faq is None:
                db.add(FAQItem(**payload))
                created += 1
            else:
                for key, value in payload.items():
                    setattr(faq, key, value)
                updated += 1
        db.commit()
        print(f"created={created} updated={updated} total={db.query(FAQItem).count()}")
        rows = (
            db.query(FAQItem.category, func.count(FAQItem.id))
            .filter(FAQItem.source == SOURCE)
            .group_by(FAQItem.category)
            .order_by(FAQItem.category)
            .all()
        )
        for category, count in rows:
            print(f"{category}: {count}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
